// Pulls the current champion list from Riot's Data Dragon, merges in the
// hand-entered facts from extra.mjs, and writes js/data.js.
// Run: node scripts/build-data.mjs
import { writeFileSync } from "node:fs";
import { EXTRA, RANGE_OVERRIDE } from "./extra.mjs";

const DD = "https://ddragon.leagueoflegends.com";
const versions = await (await fetch(`${DD}/api/versions.json`)).json();
const version = versions[0];
const { data } = await (await fetch(`${DD}/cdn/${version}/data/en_US/champion.json`)).json();

const POS = { T: "Top", J: "Jungle", M: "Mid", B: "Bot", S: "Support" };
const GEN = { M: "Male", F: "Female", O: "Other" };

function resource(partype) {
  if (partype === "Mana") return "Mana";
  if (partype === "Energy") return "Energy";
  if (!partype || partype === "None") return "None";
  if (partype === "Blood Well" || partype === "Crimson Rush") return "Health";
  return "Other"; // Fury, Rage, Heat, Flow, Grit, Courage, Shield, Ferocity
}

const champs = [];
const missing = [];
for (const c of Object.values(data).sort((a, b) => a.name.localeCompare(b.name))) {
  const out = {
    id: c.id,
    name: c.name,
    title: c.title,
    tags: c.tags,
    resource: resource(c.partype),
    range: RANGE_OVERRIDE[c.id] ?? (c.stats.attackrange <= 250 ? "Melee" : "Ranged"),
  };
  const e = EXTRA[c.id];
  if (e) {
    const [g, p, s, r, y] = e.split("|");
    out.gender = GEN[g];
    out.positions = p.split(",").map((x) => POS[x]);
    out.species = s.split(",");
    out.regions = r.split(",");
    out.year = Number(y);
  } else missing.push(c.id);
  champs.push(out);
}

const js =
  `// Generated by scripts/build-data.mjs from Data Dragon ${version}. Do not edit.\n` +
  `export const DD_VERSION = ${JSON.stringify(version)};\n` +
  `export const CHAMPS = ${JSON.stringify(champs)};\n`;
writeFileSync(new URL("../js/data.js", import.meta.url), js);
console.log(`Wrote ${champs.length} champions (Data Dragon ${version}).`);
if (missing.length) console.log(`No extra facts for: ${missing.join(", ")} (Wordle only).`);
const unused = Object.keys(EXTRA).filter((k) => !data[k]);
if (unused.length) console.log(`Extra facts for unknown ids: ${unused.join(", ")}`);
